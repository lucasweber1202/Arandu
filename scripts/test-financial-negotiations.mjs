import assert from 'node:assert/strict';
import { Readable } from 'node:stream';
import { handleFinance } from '../lib/api/domains/finance.mjs';
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
const [org, contract, rfq, opportunity, decision, proposal, outcome] = [1, 2, 3, 4, 5, 6, 7].map(id);
process.env.SUPABASE_URL = 'https://supabase.example.invalid';
process.env.SUPABASE_ANON_KEY = 'anon'; delete process.env.SUPABASE_SERVICE_ROLE_KEY;
let calls = [], hidden = false, missingOrigin = false;
globalThis.fetch = async (url, options) => {
  const path = String(url); calls.push({ path, options }); let rows = [];
  if (path.includes('fin_organizations?')) rows = [{ id: org, kind: 'BUYER' }];
  if (path.includes('fin_contracts?') && !hidden) rows = path.includes('decision_id=in.') ? [{ id: outcome, decision_id: decision, status: 'active' }] : [{ id: contract, organization_id: org }];
  if (path.includes('fin_events?') && path.includes('rfq_created_from_contract') && !missingOrigin) rows = [{ id: id(8), entity_id: rfq, metadata: { contract_id: contract, contract_version: 1 } }];
  if (path.includes('fin_rfqs?')) rows = [{ id: rfq, status: 'decided', revision: 2 }];
  if (path.includes('fin_proposals?')) rows = [{ id: proposal, rfq_id: rfq, current_version: 2 }];
  if (path.includes('fin_proposal_versions?')) rows = [{ proposal_id: proposal, version: 1, terms: { mdr_debit: 1 } }, { proposal_id: proposal, version: 2, terms: { mdr_debit: 2 } }];
  if (path.includes('fin_decisions?')) rows = [{ id: decision, rfq_id: rfq, snapshot: { selected_version: 1 } }];
  if (path.includes('fin_opportunities?') && !hidden) rows = [{ id: opportunity, organization_id: org, linked_rfq_id: rfq }];
  if (path.includes('rpc/fin_complete_opportunity_negotiation')) return Response.json({ status: 'acted', decision_id: decision, replayed: false });
  return Response.json(rows);
};
async function call(path, method = 'GET', body = null, suffix = '') {
  const req = Object.assign(Readable.from(body ? [JSON.stringify(body)] : []), { method, url: `/api/finance/${path}${suffix}`, headers: {} });
  const res = { setHeader() {}, end(v) { this.body = JSON.parse(v); } };
  await handleFinance(req, res, path, { requireUser: async () => ({ user: { id: id(10) }, accessToken: 'actor-jwt' }), enforceRateLimit: async () => {} });
  return res.body;
}
let result = await call('contract-negotiations', 'GET', null, `?contract_id=${contract}`);
assert.equal(result.processes[0].origin.contract_version, 1);
assert.equal(result.processes[0].proposals[0].versions.length, 2);
assert.equal(result.processes[0].decisions[0].snapshot.selected_version, 1);
assert.equal(result.processes[0].resulting_contracts[0].id, outcome);
assert.equal(result.processes[0].next_action.kind, 'monitor_contract');
assert.ok(calls.every(c => c.options.headers.Authorization === 'Bearer actor-jwt'));
assert.ok(calls.every(c => !c.options.method || c.options.method === 'GET'));
result = await call('opportunities/outcome', 'GET', null, `?id=${opportunity}`);
assert.equal(result.processes[0].resulting_contracts[0].id, outcome);
missingOrigin = true;
result = await call('contract-negotiations', 'GET', null, `?contract_id=${contract}`);
assert.equal(result.absence, 'no_recorded_renegotiation_origin');
assert.equal(result.processes.length, 0, 'imported contract does not acquire a fictional RFQ');
calls = []; hidden = true;
await assert.rejects(() => call('contract-negotiations', 'GET', null, `?contract_id=${contract}`), e => e.status === 404);
assert.equal(calls.length, 1, 'denied root stops traversal');
const body = { opportunity_id: opportunity, decision_id: decision, expected_status: 'acknowledged', confirmed: true, resolution: 'Human review complete' };
assert.equal((await call('opportunities/complete-negotiation', 'POST', body)).status, 'acted');
assert.equal(JSON.parse(calls.at(-1).options.body).p_decision, decision);
calls = [];
await assert.rejects(() => call('opportunities/complete-negotiation', 'POST', { ...body, confirmed: false }), e => e.status === 400);
assert.equal(calls.length, 0);
console.log('Negotiation APIs: versioned origins, outcomes, authorized reads and confirmed command PASS (HTTP mocks)');
