import assert from 'node:assert/strict';
import { restoreSchemaFingerprint as fingerprint } from '../lib/restore-schema-fingerprint.mjs';
const table='CREATE TABLE public.t (id integer NOT NULL, value integer DEFAULT 7);\n';
const option=(text,column='id')=>`ALTER TABLE ONLY public.t ALTER COLUMN ${column} SET (${text});\n`;
const hash=(text,checks=[])=>fingerprint(text,checks);
assert.equal(hash(table+option('pg_attver=123')),hash(table+option('pg_attver=456')));
assert.equal(hash(table+option('pg_attver=123')),hash(table));
assert.equal(hash(table+option('pg_attver=123','"position"')),hash(table));
assert.equal(hash(table+option('pg_attver=123, n_distinct=0.25')),hash(table+option('n_distinct=0.25')));
assert.equal(hash(table+option('n_distinct=0.25, pg_attver=456')),hash(table+option('n_distinct=0.25')));
assert.notEqual(hash(table+option('pg_attver=123, n_distinct=0.25')),hash(table+option('pg_attver=456, n_distinct=0.5')));
assert.notEqual(hash(table+option('pg_attver_like=123')),hash(table));
assert.notEqual(hash(table+option("pg_attver='123'")),hash(table));
assert.notEqual(hash(table+option("custom='pg_attver=1, keep', pg_attver=123")),hash(table+option("custom='pg_attver=2, keep', pg_attver=456")));
assert.equal(hash(table+option("custom='it''s, pg_attver=1', pg_attver=123")),hash(table+option("custom='it''s, pg_attver=1', pg_attver=456")));
for(const changed of [table.replace('integer NOT NULL','bigint NOT NULL'),table.replace(' NOT NULL',''),table.replace('DEFAULT 7','DEFAULT 8')])assert.notEqual(hash(table),hash(changed));
const check=['public','t','logic','CHECK (a AND (b OR c))',true];
assert.notEqual(hash(table,[check]),hash(table,[[...check.slice(0,3),'CHECK ((a AND b) OR c)',true]]));
assert.notEqual(hash(table,[check]),hash(table,[[...check.slice(0,4),false]]));
assert.notEqual(hash(table+'CREATE VIEW public.v AS SELECT 1;'),hash(table+'CREATE VIEW public.v AS SELECT 2;'));
assert.throws(()=>hash(table,[['incomplete']]),/Invalid CHECK/);
console.log('Restore fingerprint: only internal numeric pg_attver ignored; mixed semantic options, quoted identifiers/literals, defaults/types/nullability, CHECK grouping/validation and views remain protected.');
